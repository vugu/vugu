var ErrGoInScriptTag = errors.New("\"<script application/x-go>\" tags are no longer supported in a .vugu file.")
var ErrUnexpectedTopLevelTag = errors.New("unexpected top level tag found.")

type parseGoState struct {
	isFullHTML  bool         // is the first node an <html> tag
	docNodeList []*html.Node // top level nodes parsed out of source file
	goBuf       bytes.Buffer // additional Go code (at top)
	buildBuf    bytes.Buffer // Build() method Go code (below)
	goBufBottom bytes.Buffer // additional Go code that is put as the very last thing
	// cssChunkList []codeChunk
	// jsChunkList  []codeChunk
	outIsSet bool // set to true when vgout.Out has been set for to the level node
}

// ParserGo is a template parser that emits Go source code that will construct the appropriately wired VGNodes.
type ParserGo struct {
	PackageName string // name of package to use at top of files
	StructType  string // just the struct name, no "*" (replaces ComponentType and DataType)
	// ComponentType string // just the struct name, no "*"
	// DataType      string // just the struct name, no "*"

	NoOptimizeStatic bool // set to true to disable optimization of static blocks of HTML into vg-html expressions
	parseGoState
}

// Parse is an experiment...
// r is the actual input
func (p *ParserGo) Parse(r io.Reader) ([]byte, error) {
	// log.Printf("isFullHTML: %v", p.isFullHTML)

	// The html parser will parse the contents of the supplied *.vugu file
	// STARTING from the top most <div> tag (which is not including in the parsing)
	// and returns a *Node tree from that point downwards.
	// as a result it is impossible to for the top node to be a
	// <html> <head> or <body> node (or any node other then <div>)
	// So full HTML mode makes no sense. Any <html> etc. tag inside a <div>
	// will be ignored by the parser. However in ignored tags contents will not be
	// ignored if they are valid HTML at that point (after the tag is ignored)
	// So a nested <html> containing a <p> will ignore the <html> tag but respect the <p> tag.
	nlist, err := html.ParseFragment(r, &html.Node{
		Type:     html.ElementNode,
		DataAtom: atom.Div,
		Data:     "div",
	})
	if err != nil {
		fmt.Printf("html.ParseFragment error %s\n", err)
		return nil, err
	}

	// only add elements
	for _, n := range nlist {
		if n.Type != html.ElementNode {
			continue
		}
		// log.Printf("FRAGMENT: %#v", n)
		p.docNodeList = append(p.docNodeList, n)
	}

	//var err error
	// run n through the optimizer and convert large chunks of static elements into
	// vg-html attributes, this should provide a significiant performance boost for static HTML
	if !p.NoOptimizeStatic {
		for _, n := range p.docNodeList {
			err = compactNodeTree(n)
			if err != nil {
				fmt.Printf("compact node tree error: %s\n", err)
				return nil, err
			}
		}
	}

	// log.Printf("parsed document looks like so upon start of parsing:")
	// for i, n := range p.docNodeList {
	// 	var buf bytes.Buffer
	// 	err := html.Render(&buf, n)
	// 	if err != nil {
	// 		return fmt.Errorf("error during debug render: %v", err)
	// 	}
	// 	log.Printf("p.docNodeList[%d]:\n%s", i, buf.Bytes())
	// }

	err = p.visitOverall()
	if err != nil {
		fmt.Printf("visitOverall error: %s\n", err)
		return nil, err
	}

	var buf bytes.Buffer
	// log.Printf("goBuf.Len == %v", goBuf.Len())
	buf.Write(p.goBuf.Bytes())
	buf.Write(p.buildBuf.Bytes())
	buf.Write(p.goBufBottom.Bytes())

	// use the go/format package rather than call 'gofmt'
	fo, err := format.Source(buf.Bytes())
	if err != nil {
		// if the gofmt errors, we still attempt to write out the non-fmt'ed output to the stdout, to assist in debugging
		fmt.Printf("GO FMT ERRORS WITH %s\n%s\n", buf.String(), err)
		return nil, err
	}

	return fo, nil
}

func (p *ParserGo) visitOverall() error {
	// change the comment so that the first line matches the standard form found in a Go generate file.
	// See: https://pkg.go.dev/cmd/go#hdr-Generate_Go_files_by_processing_source
	// The new second line tells the user to regenerate
	fmt.Fprintf(&p.goBuf, "// Code generated by vugu via vugugen DO NOT EDIT.\n// Please regenerate instead of editing or add additional code in a separate file.\n\n")
	fmt.Fprint(&p.goBuf, "//go:build js && wasm\n\n")
	fmt.Fprintf(&p.goBuf, "package %s\n\n", p.PackageName)
	fmt.Fprintf(&p.goBuf, "import %q\n", "fmt")
	fmt.Fprintf(&p.goBuf, "import %q\n", "reflect")
	fmt.Fprintf(&p.goBuf, "import %q\n", "github.com/vugu/vjson")
	fmt.Fprintf(&p.goBuf, "import %q\n", "github.com/vugu/vugu/v2")
	fmt.Fprintf(&p.goBuf, "import %q\n", "syscall/js")
	fmt.Fprintf(&p.goBuf, "import %q\n", "log")
	fmt.Fprintf(&p.goBuf, "\n")

	// TODO: we use a prefix like "vg" as our namespace; should document that user code should not use that prefix to avoid conflicts
	fmt.Fprintf(&p.buildBuf, "func (c *%s) Build(vgin *vugu.BuildIn) (vgout *vugu.BuildOut) {\n", p.StructType)
	fmt.Fprintf(&p.buildBuf, "    \n")
	fmt.Fprintf(&p.buildBuf, "    vgout = &vugu.BuildOut{}\n")
	fmt.Fprintf(&p.buildBuf, "    \n")
	fmt.Fprintf(&p.buildBuf, "    var vgiterkey interface{}\n")
	fmt.Fprintf(&p.buildBuf, "    _ = vgiterkey\n")
	fmt.Fprintf(&p.buildBuf, "    var vgn *vugu.VGNode\n")
	// fmt.Fprintf(&buildBuf, "    var vgparent *vugu.VGNode\n")

	// NOTE: Use things that are lightweight here - e.g. don't do var _ = fmt.Sprintf because that brings in all of the
	// (possibly quite large) formatting code, which might otherwise be avoided.
	fmt.Fprintf(&p.goBufBottom, "// 'fix' unused imports\n")
	fmt.Fprintf(&p.goBufBottom, "var _ fmt.Stringer\n")
	fmt.Fprintf(&p.goBufBottom, "var _ reflect.Type\n")
	fmt.Fprintf(&p.goBufBottom, "var _ vjson.RawMessage\n")
	fmt.Fprintf(&p.goBufBottom, "var _ js.Value\n")
	fmt.Fprintf(&p.goBufBottom, "var _ log.Logger\n")
	fmt.Fprintf(&p.goBufBottom, "\n")

	// remove document node if present
	if len(p.docNodeList) == 1 && p.docNodeList[0].Type == html.DocumentNode {
		p.docNodeList = []*html.Node{p.docNodeList[0].FirstChild}
	}

	gotTopNode := false

	for _, n := range p.docNodeList {

		// ignore comments
		if n.Type == html.CommentNode {
			continue
		}

		if n.Type == html.TextNode {

			// ignore whitespace text
			if strings.TrimSpace(n.Data) == "" {
				continue
			}

			// error on non-whitespace text
			return fmt.Errorf("unexpected text outside any element: %q", n.Data)

		}

		// must be an element at this point
		if n.Type != html.ElementNode {
			return fmt.Errorf("unexpected node type %v; node=%#v", n.Type, n)
		}

		if isScriptOrStyle(n) {

			err := p.visitScriptOrStyle(n)
			if err != nil {
				return err
			}
			continue
		}

		if gotTopNode {
			return fmt.Errorf("Found more than one top level element: %s", n.Data)
		}
		gotTopNode = true

		// handle top node
		// check for forbidden top level tags
		// Commented out for clarity -as this code may reappear.
		// But.....
		// html.ParseFragment is set to start from the first <div> element it sees in the supplied file.
		// Any extra top level tags e.g. <head> will have already been stripped by html.ParseFragment
		// As a result this if test is ALWAYS false.
		// Test TestParserTopLevelTag confirms this as it should never fail
		nodeName := strings.ToLower(n.Data)
		if nodeName == "head" ||
			nodeName == "body" ||
			nodeName == "html" {
			return fmt.Errorf("%v: %w", nodeName, ErrUnexpectedTopLevelTag)
		}

		err := p.visitTopNode(n)
		if err != nil {
			return err
		}
		continue

	}

	fmt.Fprintf(&p.buildBuf, "    return vgout\n")
	fmt.Fprintf(&p.buildBuf, "}\n\n")

	return nil
}

// visitTopNode handles the "mount point"
func (p *ParserGo) visitTopNode(n *html.Node) error {
	// handle the top element other than <html>

	err := p.visitNodeJustElement(n)
	if err != nil {
		return err
	}

	return nil
}

// visitNodeElementAndCtrl handles an element that supports vg-if, vg-for etc
func (p *ParserGo) visitNodeElementAndCtrl(n *html.Node) error {
	// vg-for
	if v, _ := vgForExpr(n); v.expr != "" {
		if err := p.emitForExpr(n); err != nil {
			return err
		}
		defer fmt.Fprintf(&p.buildBuf, "}\n")
	}

	// vg-if
	ife := vgIfExpr(n)
	if ife != "" {
		fmt.Fprintf(&p.buildBuf, "if %s {\n", ife)
		defer fmt.Fprintf(&p.buildBuf, "}\n")
	}

	err := p.visitNodeJustElement(n)
	if err != nil {
		return err
	}

	return nil
}

// visitNodeJustElement handles an element, ignoring any vg-if, vg-for (but it does handle vg-html - since that is not really "control" just a shorthand for it's contents)
func (p *ParserGo) visitNodeJustElement(n *html.Node) error {
	// regular element

	p.pOutputTag(n)
	// fmt.Fprintf(&p.buildBuf, "vgn = &vugu.VGNode{VGNodeCommonCore: vugu.VGNodeCommonCore{Type:vugu.VGNodeType(%d),Data:%q,Attr:%#v}}\n", n.Type, n.Data, staticVGAttr(n.Attr))
	// if p.outIsSet {
	// 	fmt.Fprintf(&p.buildBuf, "vgparent.AppendChild(vgn)\n") // if not root, make AppendChild call
	// } else {
	// 	fmt.Fprintf(&p.buildBuf, "vgout.Out = append(vgout.Out, vgn) // root for output\n") // for first element we need to assign as Doc on BuildOut
	// 	p.outIsSet = true
	// }

	// dynamic attrs
	p.writeDynamicAttributes(n)

	// vg-js-*
	p.writeJSCallbackAttributes(n)

	// js properties
	propExprMap, propExprMapKeys := propVGAttrExpr(n)
	for _, k := range propExprMapKeys {
		valExpr := propExprMap[k]
		fmt.Fprintf(&p.buildBuf, "{b, err := vjson.Marshal(%s); if err != nil { panic(err) }; vgn.Prop = append(vgn.Prop, vugu.VGProperty{Key:%q,JSONVal:vjson.RawMessage(b)})}\n", valExpr, k)
	}

	// vg-html
	htmlExpr := vgHTMLExpr(n)
	if htmlExpr != "" {
		fmt.Fprintf(&p.buildBuf, "vgn.SetInnerHTML(%s)\n", htmlExpr)
	}

	// DOM events
	eventMap, eventKeys := vgDOMEventExprs(n)
	for _, k := range eventKeys {
		expr := eventMap[k]
		fmt.Fprintf(&p.buildBuf, "vgn.DOMEventHandlerSpecList = append(vgn.DOMEventHandlerSpecList, vugu.DOMEventHandlerSpec{\n")
		fmt.Fprintf(&p.buildBuf, "EventType: %q,\n", k)
		fmt.Fprintf(&p.buildBuf, "Func: func(event vugu.DOMEvent) { %s },\n", expr)
		fmt.Fprintf(&p.buildBuf, "// TODO: implement capture, etc. mostly need to decide syntax\n")
		fmt.Fprintf(&p.buildBuf, "})\n")
	}

	if n.FirstChild != nil {

		fmt.Fprintf(&p.buildBuf, "{\n")
		fmt.Fprintf(&p.buildBuf, "vgparent := vgn; _ = vgparent\n") // vgparent set for this block to vgn

		// iterate over children
		for childN := n.FirstChild; childN != nil; childN = childN.NextSibling {

			err := p.visitDefaultByType(childN)
			if err != nil {
				return err
			}
		}

		fmt.Fprintf(&p.buildBuf, "}\n")

	}

	return nil
}

func (p *ParserGo) visitDefaultByType(n *html.Node) error {
	// handle child according to type
	var err error
	switch {
	case n.Type == html.CommentNode:
		err = p.visitNodeComment(n)
	case n.Type == html.TextNode:
		err = p.visitNodeText(n)
	case n.Type == html.ElementNode:
		// we no longer support pkg:struct its not a <vg-type> tag. There is now no namespace conflict
		if n.Data == "vg-type" {
			// NOTE: this should check for a capital letter after the colon - this would distinguish
			// svg:svg (valid regular HTML) from svg:Svg (a component reference)
			err = p.visitNodeComponentElement(n)
		} else if n.Data == "vg-comp" {
			err = p.visitVGCompTag(n)
		} else if n.Data == "vg-template" {
			err = p.visitVGTemplateTag(n)
		} else {
			err = p.visitNodeElementAndCtrl(n)
		}
	default:
		return fmt.Errorf("child node of unknown type %v: %#v", n.Type, n)
	}

	if err != nil {
		return err
	}

	return nil
}

func (p *ParserGo) visitNodeText(n *html.Node) error {
	fmt.Fprintf(&p.buildBuf, "vgn = &vugu.VGNode{VGNodeCommonCore: vugu.VGNodeCommonCore{Type:vugu.VGNodeType(%d),Data:%q}}\n", n.Type, n.Data)
	fmt.Fprintf(&p.buildBuf, "vgparent.AppendChild(vgn)\n")

	return nil
}

func (p *ParserGo) visitNodeComment(n *html.Node) error {
	fmt.Fprintf(&p.buildBuf, "vgn = &vugu.VGNode{VGNodeCommonCore: vugu.VGNodeCommonCore{Type:vugu.VGNodeType(%d),Data:%q}}\n", n.Type, n.Data)
	fmt.Fprintf(&p.buildBuf, "vgparent.AppendChild(vgn)\n")

	return nil
}

// visitVGCompTag handles a vg-comp
func (p *ParserGo) visitVGCompTag(n *html.Node) error {
	// vg-for not allowed here

	// vg-if is supported
	ife := vgIfExpr(n)
	if ife != "" {
		fmt.Fprintf(&p.buildBuf, "if %s {\n", ife)
		defer fmt.Fprintf(&p.buildBuf, "}\n")
	}

	// for now, nothing else supported

	// must have a "expr" which gives the Go expression which will result in a component
	expr := vgCompExpr(n)
	if expr == "" {
		return fmt.Errorf("vg-comp must have an `expr` attribute with a Go expression in it")
	}
	fmt.Fprintf(&p.buildBuf, "{\n")
	defer fmt.Fprintf(&p.buildBuf, "}\n")

	fmt.Fprintf(&p.buildBuf, "var vgcomp vugu.Builder = %s\n", expr)
	fmt.Fprintf(&p.buildBuf, "if vgcomp != nil {\n")
	fmt.Fprintf(&p.buildBuf, "    vgin.BuildEnv.WireComponent(vgcomp)\n")
	fmt.Fprintf(&p.buildBuf, "    vgout.Components = append(vgout.Components, vgcomp)\n")
	fmt.Fprintf(&p.buildBuf, "    vgn = &vugu.VGNode{VGNodeCommonCore: vugu.VGNodeCommonCore{Component:vgcomp}}\n")
	fmt.Fprintf(&p.buildBuf, "    vgparent.AppendChild(vgn)\n")
	fmt.Fprintf(&p.buildBuf, "}\n")

	return nil
}

// visitVGTemplateTag handles vg-template
func (p *ParserGo) visitVGTemplateTag(n *html.Node) error {
	// vg-for
	if v, _ := vgForExpr(n); v.expr != "" {
		if err := p.emitForExpr(n); err != nil {
			return err
		}
		defer fmt.Fprintf(&p.buildBuf, "}\n")
	}

	// vg-if
	ife := vgIfExpr(n)
	if ife != "" {
		fmt.Fprintf(&p.buildBuf, "if %s {\n", ife)
		defer fmt.Fprintf(&p.buildBuf, "}\n")
	}

	// output a node with type Element but empty data
	fmt.Fprintf(&p.buildBuf, "vgn = &vugu.VGNode{VGNodeCommonCore: vugu.VGNodeCommonCore{Type:vugu.VGNodeType(%d)}} // <vg-template>\n", vugu.ElementNode)
	fmt.Fprintf(&p.buildBuf, "vgparent.AppendChild(vgn)\n")

	// and then only process children
	if n.FirstChild != nil {

		fmt.Fprintf(&p.buildBuf, "{\n")
		fmt.Fprintf(&p.buildBuf, "vgparent := vgn; _ = vgparent\n") // vgparent set for this block to vgn

		// iterate over children
		for childN := n.FirstChild; childN != nil; childN = childN.NextSibling {

			err := p.visitDefaultByType(childN)
			if err != nil {
				return err
			}
		}

		fmt.Fprintf(&p.buildBuf, "}\n")

	}

	return nil
}

// NOTE: caller is responsible for emitting the closing curly bracket
func (p *ParserGo) emitForExpr(n *html.Node) error {
	forattr, err := vgForExpr(n)
	if err != nil {
		return err
	}
	forx := forattr.expr
	if forx == "" {
		return errors.New("no for expression, code should not be calling emitForExpr when no vg-for is present")
	}

	// cases to select vgiterkey:
	// * check for vg-key attribute
	// * _, v := // replace _ with vgiterkey
	// * key, value := // unused vars, use 'key' as iter val
	// * k, v := // detect `k` and use as iterval

	// determine iteration variables
	var shortcutCase bool
	if !strings.Contains(forx, ":=") {
		// make it so `w` is a shorthand for `key, value := range w`
		// iterkey = "key" b
		forx = "key, value := range " + forx
		shortcutCase = true
	}

	fmt.Fprintf(&p.buildBuf, "for %s {\n", forx)
	if shortcutCase {
		// we have no way to know if the "key" or "value" loop variables are used
		// wholly within the HTML tag the vg-for attribute is applied to like this:
		// <li vgfor=`c.Items()` vg-content='fmt.Sprintf("%s\n", value)'></li>
		// Where the content of the <li> tag uses the "value" loop variabele directly
		// OR
		// if a loop variable is used within an inner tag, like this:
		// <li vg-for='c.Items()'>
		//      <div vg-content='fmt.Sprintf("%s\n", value)'></div>
		// </li>
		// Now the use of the "value" is in the enclosed <div> not the <li>
		// OR
		// the loop variables may never be used, like this:
		// <li vg-for='c.Items()' vg-content='fmt.Sprintf("Hello World\n")'></li>
		// Without parsing the rest of *.vugu file it is impossible to answer these questions.
		// Therefore the only (sub-optimal) choice we have is to always add unused references to these
		// variables. Without these the Go compiler will correctly fail with a "variable declared but
		// not used" error.
		fmt.Fprintf(&p.buildBuf, "_ = key\n_ = value\n")
	}
	return nil
}

func hasUpperFirst(s string) bool {
	for _, c := range s {
		return unicode.IsUpper(c)
	}
	return false
}

// isScriptOrStyle returns true if this is a "script", "style" or "link" tag
func isScriptOrStyle(n *html.Node) bool {
	if n.Type != html.ElementNode {
		return false
	}
	switch strings.ToLower(n.Data) {
	case "script", "style", "link":
		return true
	}
	return false
}

func (p *ParserGo) pOutputTag(n *html.Node) {
	fmt.Fprintf(&p.buildBuf, "vgn = &vugu.VGNode{VGNodeCommonCore: vugu.VGNodeCommonCore{Type:vugu.VGNodeType(%d),Namespace:%q,Data:%q,Attr:%#v}}\n", n.Type, n.Namespace, n.Data, staticVGAttr(n.Attr))
	if p.outIsSet {
		fmt.Fprintf(&p.buildBuf, "vgparent.AppendChild(vgn)\n") // if not root, make AppendChild call
	} else {
		fmt.Fprintf(&p.buildBuf, "vgout.Out = append(vgout.Out, vgn) // root for output\n") // for first element we need to assign as Doc on BuildOut
		p.outIsSet = true
	}
}

func attrWithKey(n *html.Node, key string) *html.Attribute {
	for i := range n.Attr {
		if n.Attr[i].Key == key {
			return &n.Attr[i]
		}
	}
	return nil
}

func (p *ParserGo) writeDynamicAttributes(n *html.Node) {
	dynExprMap, dynExprMapKeys := dynamicVGAttrExpr(n)
	for _, k := range dynExprMapKeys {
		valExpr := dynExprMap[k]
		if k == "" || k == "vg-attr" {
			fmt.Fprintf(&p.buildBuf, "vgn.AddAttrList(%s)\n", valExpr)
		} else {
			fmt.Fprintf(&p.buildBuf, "vgn.AddAttrInterface(%q,%s)\n", k, valExpr)
		}
	}
}

// writeJSCallbackAttributes handles vg-js-create and vg-js-populate
func (p *ParserGo) writeJSCallbackAttributes(n *html.Node) {
	m := jsCallbackVGAttrExpr(n)
	createStmt := m["vg-js-create"]
	if createStmt != "" {
		fmt.Fprintf(&p.buildBuf, "vgn.JSCreateHandler = vugu.JSValueFunc(func(value js.Value) { %s })\n", createStmt)
	}
	populateStmt := m["vg-js-populate"]
	if populateStmt != "" {
		fmt.Fprintf(&p.buildBuf, "vgn.JSPopulateHandler = vugu.JSValueFunc(func(value js.Value) { %s })\n", populateStmt)
	}
}
